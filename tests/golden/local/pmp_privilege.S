// 一条黄金语料：**PMP 的「特权口径」** —— 一次访问到底受不受 PMP 约束，
// 取决于它的**有效特权级**，而不只是 `mstatus.MPRV` 这一位。
//
// RISC-V 特权规范（§3.7.6）的口径是：
//
//   * **数据访问**（load / store）的有效特权级 = `MPRV` ? `MPP` : 当前特权级；
//   * **取指**永远用**当前**特权级（`MPRV` 对取指**不**起作用）；
//   * **有效特权级 == M ⇒ 豁免 PMP**（除非命中了一个**被锁住**的条目）。
//
// ⚠️ 平台把这条**塌缩成「只看 `MPRV`」**（取指那一支更极端：**无条件豁免**）
// ⇒ ⇒ 于是**三个方向**都错：
//   * **(a) 平台过严**：`MPRV` = 1 且 `MPP` = 3（M）时，有效特权级是 M
//     ⇒ ⇒ 应当**豁免**（放行），平台却**仍然施加** PMP ⇒ ⇒ 拒。
//   * **(b) 平台过松（⚠️ 安全方向的漏洞）**：**S 模式**且 `MPRV` = 0 时，
//     有效特权级是 S ⇒ ⇒ 应当**施加** PMP，平台却**豁免** ⇒ ⇒ 放行
//     ⇒ ⇒ S 模式的代码能访问它不该访问的内存。
//   * **(c) 平台过松（⚠️ 安全方向的漏洞）**：**取指**的豁免是**无条件**的 ⇒ ⇒
//     S 模式的取指落进一条**没有 `X` 权限**的条目，参考侧**拒**
//     （`mcause` = 1，instruction access fault），平台却**放行**。
//
// 台账 **D-153** 登记的正是 (a) 与 (b)（它们**一个根因**：有效特权级那个公式
// 塌缩成了「`MPRV` == 0」）；(c) 是**取指**那一支的同一个病根的另一个症状 ⇒ ⇒
// 本条语料把**三个症状**都钉住。
//
// ⚠️ **本条语料断言的是「参考侧（Spike）的行为」**，不是我们平台当前的行为
// ⇒ ⇒ 平台改之前它**在平台侧一定是红的** ⇒ ⇒ **那行红本身就是判别力证据**
// ⇒ ⇒ ⛔ **不许**为了让平台侧变绿而把断言改软。
//
// ---------------------------------------------------------------------------
// 钉住什么：五格
// ---------------------------------------------------------------------------
// **一条程序**把五格**全部**跑完（⚠️ 必须同一条程序 ⇒ ⇒ 否则「只改了一半
// 的实现」会看起来绿 ⇒ ⇒ 判定必须**逐格独立**）。
//
// 数据格共用同一个地址 `T` = `0x8004_0000`（落在 DENY 条目里），只改**特权
// 口径**；取指格另有一个目标地址（同一条 DENY 条目，但看的是 `X` 权限）：
//
// | 格 | 当前特权级 | `MPRV` | `MPP` | 有效特权级 | 访问 | 期望 |
// | --- | --- | --- | --- | --- | --- | --- |
// | A | M | 0 | 0 | **M** | load @ `T` | **放行**，且读回的值必须是预填的值 |
// | B | M | 1 | 0 (U) | **U** | load @ `T` | **拒绝** ⇒ 陷阱，`mcause` = 5 |
// | C | M | 1 | 3 (M) | **M** | load @ `T` | **放行**，且读回的值必须是预填的值 |
// | D | **S** | 0 | 任意 | **S** | load @ `T` | **拒绝** ⇒ 陷阱，`mcause` = 5 |
// | E | **S** | 0 | 任意 | **S**（取指用当前特权级） | **取指** @ `T` | **拒绝** ⇒ 陷阱，`mcause` = 1 |
//
// ⚠️ **格 C 与格 D 缺一不可**：格 A 单独测**零判别力**（旧实现与新实现同
// 结果）⇒ ⇒ 判别力**只**在格 C（抓 (a)，平台过严）与格 D（抓 (b)，平台
// 过松、⚠️ 安全方向）这两格上 ⇒ ⇒ 两者**都要**在。
//
// ⚠️ **格 E 与格 D 也不是彼此的替代品**：格 D 走**数据**路径（`Load`），
// 格 E 走**取指**路径（`Fetch`）⇒ ⇒ 平台旧实现里这是**两行不同的代码**
// （数据那一支的 `m_mode_bypass` 与取指那一支的「无条件豁免」）⇒ ⇒ 只钉
// 其一 ⇒ ⇒ 另一半的漏洞就漏过去 ⇒ ⇒ 两格都要在。
//
// ⚠️ 另外两格也**不是**多余的：格 A 与格 B 的**唯一**差别是 `MPRV` 这一位
// ⇒ ⇒ 这一对把「`MPRV` 的作用」单独钉住（`MPRV` 的作用是**把 load/store
// 的有效特权级换成 `MPP`**，**不是**「打开检查」—— 这两件事不一样）。
//
// ---------------------------------------------------------------------------
// ⚠️ **只有第一个失败的格会被报出来** ⇒ ⇒ 每修一格就要复跑一次才能看到下一格
// ---------------------------------------------------------------------------
// 判决是**一个数**（`tohost` 的退出码）⇒ ⇒ 程序只能报出**第一个**失败的格
// ⇒ ⇒ 平台侧一次只能看见一个症状 ⇒ ⇒ **修完一格必须复跑**才能看到下一格。
//
// ⇒ ⇒ 所以顺序要**按「信息量」**排：**先跑会立刻暴露平台旧实现错误的那几格**
// ⇒ ⇒ 也就是把**抓点**（C / D / E）放在**对照**（A / B）**前面**？⇒ ⇒ **不**是：
// 对照格的作用是「**配置对不对**」的体检 ⇒ ⇒ 它坏了 ⇒ ⇒ 后面所有格的判决都
// 失去意义 ⇒ ⇒ **对照必须在前**。⇒ ⇒ 于是顺序这样定：
//
//   * **控制组**（ALLOW 区间的一次访问）**最先**⇒ ⇒ 配置坏了它先报；
//   * **格 A / 格 B**（旧实现与新实现**一致**的那两格）**紧随其后**⇒ ⇒ 它们
//     是「`MPRV` 语义」的对照 ⇒ ⇒ 坏了 ⇒ ⇒ 说明不是特权口径的问题；
//   * **格 C**（M 模式里唯一的抓点）**然后**⇒ ⇒ 它不依赖 S 模式的引导；
//   * **格 D / 格 E**（S 模式的两格）**最后**⇒ ⇒ 它们依赖「进 S 模式」这件
//     事 ⇒ ⇒ 放最后 ⇒ ⇒ 一来 S 模式的引导**只做一次**、不需要「回 M 模式」
//     的额外机制，二来 M 模式那部分的判决**不会**被 S 模式引导的问题掩盖。
//
// ⇒ ⇒ **注意**：在这个顺序下，改前的平台报的是**格 C** 的失败码 ⇒ ⇒ 想要
// 看见格 D / 格 E 的失败码 ⇒ ⇒ 得先把格 C 修好再复跑 ⇒ ⇒ 这就是「一个数」
// 的代价 ⇒ ⇒ 我用**仓外探针**把那两格的失败码**分别**测了出来（见报告）。
//
// ---------------------------------------------------------------------------
// PMP 配置（照抄 `pmp_straddle.S` 的配置 A）
// ---------------------------------------------------------------------------
//   entry 0: NAPOT, 4 KiB @ `0x8004_0000`, **无权限** ⇒ DENY
//             pmpaddr0 = `0x2001_01ff`（`0x80040000 >> 2` + 9 个尾随 1
//                         ⇒ 2^(9+3) = 4096 字节）
//             pmpcfg0 字节 0 = `0x18`（A = NAPOT，无 R/W/X）
//   entry 1: NAPOT, 1 MiB @ `0x8000_0000`, R + W + X ⇒ ALLOW
//             pmpaddr1 = `0x2001_ffff`（`0x80000000 >> 2` + 17 个尾随 1
//                         ⇒ 2^(17+3) = 1 MiB）
//             pmpcfg0 字节 1 = `0x1f`（A = NAPOT，R + W + X）
//
// ⇒ ⇒ 整个寄存器是 `pmpcfg0 = 0x1f18`（RV32 的 `pmpcfg0` 装**四条** 8 位
// 条目：字节 0 = 条目 0，字节 1 = 条目 1 ⇒ ⇒ 写 `pmpcfg1` 会配到条目 4..7）。
//
// ⚠️ **地址的落点**：
//   * `T` = `0x8004_0000` ⇒ **同时**落在两个条目里 ⇒ ⇒ **编号小的条目 0
//     说了算** ⇒ ⇒ DENY 生效 ⇒ ⇒ 这一格才有判别力。
//   * 控制地址 = `0x8000_2000` ⇒ 落在条目 1（ALLOW）里、**不**落在条目 0
//     里 ⇒ ⇒ 那里必须**放行**（控制组，见下）。
//   * 代码在 `0x8000_0000`、`tohost` 在 `0x8000_1000` ⇒ ⇒ 两者都在条目 1
//     里 ⇒ ⇒ **判决路径永远不会被 PMP 挡住**（本语料**没有**锁住的条目，
//     所以连「锁住的条目在所有特权级强制」那条也不会咬到判决路径）。
//
// ⚠️ **格 E 为什么只能用条目 0**：**决定条目 = 编号最小的命中条目** ⇒ ⇒ 要让
// 一次取指被**拒**，它就必须落在**编号更小**的那个条目里 ⇒ ⇒ 条目 1（ALLOW，
// 带 `X`）覆盖整个低 1 MiB ⇒ ⇒ 凡是落在条目 1 范围内的地址，取指都由条目 1
// 决定 ⇒ ⇒ **放行** ⇒ ⇒ 取指的目标只能落在条目 0 的范围里 ⇒ ⇒ 而条目 0
// **没有 `X`** ⇒ ⇒ 取指被拒。⇒ ⇒ 这一格钉的是「**取指也要看 `X` 权限**」。
//
// ⚠️ **写 `pmpcfg0` 的时机**：`pmpcfg0` **先**写一次 `0x1f1f`（两条都放行）
// ⇒ ⇒ 这样**任何中间态**都不会出现「DENY 条目盖住代码或 `tohost`」⇒ ⇒
// 程序永远不会被自己的配置锁在外面。（顺带：`mstatus.MPRV` 此时仍是 0 ⇒ ⇒
// M 模式的访存本来就豁免 PMP ⇒ ⇒ 中间态也不会咬到代码本身。）
//
// ---------------------------------------------------------------------------
// 控制组（「这个用例是活的」）
// ---------------------------------------------------------------------------
// 控制访问落在 ALLOW 区间内、且**不在** DENY 区间内 ⇒ ⇒ 读回的值必须是
// 预填的值 ⇒ ⇒ 没有它，一个「**什么都拒**」的实现也能让格 B / 格 D / 格 E
// 看起来对（因为那几格本来就期望被拒）。
//
// ⚠️ 控制**特意**跑在 **PMP 真的生效**的窗口里（`MPRV` = 1、`MPP` = 0 ⇒ ⇒
// 有效特权级 = U）⇒ ⇒ 它和格 B 在**同一个窗口**⇒ ⇒ 它证明的正是「条目 1
// 真的给了权限」，而不是「M 模式反正不受管」。
//
// ---------------------------------------------------------------------------
// 陷阱的因果检查
// ---------------------------------------------------------------------------
// 发生陷阱时：`mcause` 必须 == **5**（load access fault，数据格）或 **1**
// （instruction access fault，取指格），`mepc` 必须 == **那条出错的指令**
// （数据格）或 **那个出错的取指地址**（取指格）⇒ ⇒ 两者各有自己的失败码。
//
// ⚠️ **陷阱的落点**（参考侧实测确认）：S / U 模式下的访问故障（`mcause` 1 /
// 5 / 7）在参考侧**全部落在 `mtvec`**，且处理时处于 **M 模式** ⇒ ⇒ 本语料
// **不**委托这些 cause ⇒ ⇒ `mtvec_handler` 一律以 **M 模式**运行 ⇒ ⇒ 判决
// 写 `tohost` 时不受 PMP 约束 ✔。（`medeleg` 的掩码 `0xB10D` = 位
// {0, 2, 3, 8, 12, 13, 15} ⇒ ⇒ cause 1 / 5 / 7 都**不在**里面 ⇒ ⇒ 它们
// 本来就不会被委托。）
//
// ---------------------------------------------------------------------------
// ⚠️ 格 E 的实现细节：「跳转」与「被拒的那次取指」必须分清
// ---------------------------------------------------------------------------
// 格 E 要在 **S 模式**下**取指**到一条**没有 `X` 权限**的条目 ⇒ ⇒ 做法是
// **从 S 模式跳过去**：跳转指令本身在当前代码段（条目 1，带 `X`）⇒ ⇒ **它
// 的那次取指成功** ⇒ ⇒ **被拒的是落在目标地址的那次取指** ⇒ ⇒ 判据钉在
// **目标地址**上（`mepc` == `0x8004_0000`），**不是**钉在「跳转失败」。
//
// ⚠️ **目标地址上预填的字是 `0xfeedface`** ⇒ ⇒ 它不是一个合法指令 ⇒ ⇒
// 万一取指被**放行**（平台旧实现的症状），那一个字会被当成指令执行 ⇒ ⇒
// 非法指令（`mcause` = 2）⇒ ⇒ 于是「取指没有被拒」这件事在判决上是**看得见**
// 的 ⇒ ⇒ 不会与「被拒了但 cause 不对」混在一起。
//
// ⚠️⚠️ **而 cause 2 是被委托的** ⇒ ⇒ 那条非法指令陷阱落的是 **S 级**处理器
// （**不是** `mtvec`）⇒ ⇒ ⇒ ⇒ 所以「取指没有被拒」的证据是一条**被委托**的
// 非法指令陷阱 ⇒ ⇒ S 级处理器必须认这一条（否则它会被当成「意料之外的陷阱」
// ⇒ ⇒ 报出来的失败码就不指向「取指没有被拒」这件事了）⇒ ⇒ ⚠️ 这是实测
// 出来的：改前的平台报的是 **FAIL 14**（意料之外）而不是「取指没有被拒」
// ⇒ ⇒ 修正后才报 **FAIL 16**。
//
// ---------------------------------------------------------------------------
// ⚠️ 「我们真的在 S 模式」的**自证**（这一段不是装饰，是必须的）
// ---------------------------------------------------------------------------
// 格 D 与格 E 都要求「**当前特权级是 S**」⇒ ⇒ 如果程序其实**没进** S 模式，
// 那两格就测的根本不是 S 模式 ⇒ ⇒ 而**两侧会同时**报出同一个失败码 ⇒ ⇒
// 对拍器会把它看成「**两边一致**」⇒ ⇒ **一条假绿的语料** ⇒ ⇒ 所以这两格
// 必须**自证**。
//
// ⚠️ 本语料**真的踩过**这个坑：第一版里 `csrs mstatus, 0x800` 之后 `MPP`
// 仍然是 3（`csrs` 是**或**⇒ ⇒ 它只**置位**，不会把已经是 1 的那位清掉）
// ⇒ ⇒ `mret` 于是落回 **M 模式**⇒ ⇒ 参考侧报 FAIL 10（格 D「没有被拒」）
// ⇒ ⇒ 而平台侧会报**同一个**码 ⇒ ⇒ **两边一致 = 假绿**。⇒ ⇒ 所以：
//
//   * `MPP` 要**先清干净**（`csrc`）**再置位**（`csrs`）—— 它是个两位的
//     WARL 字段，`MPP` = 1 / 3 都合法 ⇒ ⇒ 「或」进去是错的。
//   * 进 S 模式之后，用「**读一个 M 级 CSR**」来**证明**自己在 S 模式：
//     S 模式里读 `mstatus` 是**非法指令**（cause 2）⇒ ⇒ 它**被委托**
//     （`medeleg` 的掩码含 cause 2）⇒ ⇒ 于是落到 **S 级**处理器
//     ⇒ ⇒ **能走到 S 级处理器这件事本身就是「我们在 S 模式」的证据**
//     ⇒ ⇒ 如果那条指令没陷（说明还在 M 模式）⇒ ⇒ 走一条专门的失败码。
//
// ---------------------------------------------------------------------------
// ⚠️ 失败码表（一张红行要说清「哪一格坏了」）
// ---------------------------------------------------------------------------
//   TESTNUM = 1  ->  PASS（五格全部成立）
//   TESTNUM = 3  ->  格 A：那次 load **被拒了**（必须放行）⇒ ⇒ 平台**过严**
//   TESTNUM = 4  ->  格 A：放行了但**读回的值不对**（不是预填的那个）
//   TESTNUM = 5  ->  格 B：那次 load **没有被拒** ⇒ ⇒ 平台**过松**
//   TESTNUM = 6  ->  格 B：陷阱发生了但 `mcause` **不是 5**（拒的**种类**不对）
//   TESTNUM = 7  ->  格 B：`mcause` 是 5 但 `mepc` **不是**那条出错的指令
//   TESTNUM = 8  ->  格 C：那次 load **被拒了**（必须放行）⇒ ⇒ 平台**过严**
//                    （D-153 的 (a) 那一格）
//   TESTNUM = 9  ->  格 C：放行了但**读回的值不对**
//   TESTNUM = 10 ->  格 D：那次 load **没有被拒** ⇒ ⇒ 平台**过松**
//                    （D-153 的 (b) 那一格，⚠️ **安全方向**的漏洞）
//   TESTNUM = 11 ->  格 D：陷阱发生了但 `mcause` **不是 5**
//   TESTNUM = 12 ->  格 D：`mcause` 是 5 但 `mepc` **不是**那条出错的指令
//   TESTNUM = 13 ->  **控制组**坏了（ALLOW 区间的访问没有读回预填的值）
//                    ⇒ ⇒ 这个用例**不是活的**⇒ ⇒ 其它判决都失去意义
//   TESTNUM = 14 ->  **意料之外的陷阱**（相位对不上；或 S 模式证明的
//                    `scause` 不是 2）⇒ ⇒ 说明某个前提不成立
//   TESTNUM = 15 ->  **S 模式的证明没有发生**（那条读 `mstatus` 的指令没陷）
//                    ⇒ ⇒ 程序**没有**进 S 模式 ⇒ ⇒ 格 D / 格 E 根本没被测到
//   TESTNUM = 16 ->  格 E：目标地址的那次**取指没有被拒** ⇒ ⇒ 平台**过松**
//                    （取指无条件豁免）⇒ ⇒ 那一格预填的字被当成指令执行了
//                    ⇒ ⇒ 非法指令（cause 2）⇒ ⇒ 而它**被委托**⇒ ⇒ 所以
//                    这条失败码是从 **S 级**处理器报出来的
//   TESTNUM = 17 ->  格 E：`mcause` 是 1 但 `mepc` **不是**目标地址
//
// ⇒ ⇒ 五格各有**自己**的失败码 ⇒ ⇒ 一张红行能说清**哪一格**坏了。
//
// ---------------------------------------------------------------------------
// ⚠️ 什么**没有**被断言，以及为什么
// ---------------------------------------------------------------------------
// * **`mtval` 在这一条语料里仍然不断言 —— 但理由已经变了**（台账 **D-154**
//   已由 **v0.41 批闭环**）：平台现在报的就是「**出错那一片**的起始地址」，
//   与参考侧**逐字一致** ⇒ ⇒ 断言它**会是绿的** ⇒ ⇒ 这里不断言是
//   「**不必重复**」而不是「**不能断言**」⇒ ⇒ **跨片**的那条 `mtval` 断言在
//   `local/pmp_straddle` 里（它断言 `mtval` = `0x8004_0000`）⇒ ⇒ 这一条
//   断言的是 `mcause`（它把「被拒了」与「被拒成**读访问故障** / **取指访问
//   故障**」区分开：cause 4 是错位、cause 2 是非法指令、cause 12 是取指缺页）。
// * **取指口径的另一半没有断言**：「`MPRV` 对取指**不**起作用」这条规则需要
//   **第六格**（M 模式 · `MPRV` = 1 · 取指落进无 `X` 条目 ⇒ ⇒ 仍须**放行**，
//   因为取指用**当前**特权级）⇒ ⇒ 本条语料**不做**那一格 ⇒ ⇒ 格 E 钉的是
//   「**S 模式下的取指要受检**」这一半 ⇒ ⇒ 另一半由内核侧的既有单测承担。
// * **格 D 那条陷阱落在哪里**不单独断言「必须落在 `mtvec`」：它落在 `mtvec`
//   是因为 `medeleg` 的掩码里**没有** cause 5 ⇒ ⇒ 该陷阱**不被委托**⇒ ⇒
//   它以 **M 模式**处理 ⇒ ⇒ 于是 `mcause` / `mepc`（M 级 CSR）读得到 ⇒ ⇒
//   断言成立。⚠️ 若哪一天它被**委托**了，落点会变成 S 级的 `stvec_handler`
//   ⇒ ⇒ 那条路径报 **FAIL 14**（意料之外的陷阱）⇒ ⇒ 不会伪装成通过。
//
// ---------------------------------------------------------------------------
// ⚠️ 为什么这么写
// ---------------------------------------------------------------------------
// * **一条程序跑五格**：⇒ ⇒ 「只改了一半的实现」不会看起来绿（如果五格是
//   五条独立语料，平台只改好一格时，那一格绿、另一格红，仍然能看出来；但
//   **同一条程序**能保证「跑到后面那格时，前面的格已经真的过了」）。
// * **相位寄存器 `s3` + 直接 `j`**，**不**用 `mret` 续跑（照 `pmp_straddle.S`
//   的做法）：⇒ ⇒ 格 B 的陷阱之后 `MPP` 是 0（U）⇒ ⇒ 一次 `mret` 会把 hart
//   丢进 U 模式 ⇒ ⇒ 后面的格就跑不动了 ⇒ ⇒ 所以处理器**不返回**，直接跳到
//   下一格 ⇒ ⇒ hart 一直待在 M 模式。
// * **S 模式那一段跑在最后**：⇒ ⇒ 它需要「进 S 模式」⇒ ⇒ 放最后 ⇒ ⇒
//   S 模式的引导只做一次；格 D 的陷阱之后要**回 S 模式**跑格 E ⇒ ⇒ 那是
//   一次 `mret`（`MPP` = 1）⇒ ⇒ 落回 S 模式 ⇒ ⇒ 格 E 的取指才是 S 模式的
//   取指。
// * **用 `smode` 环境，⛔ 不用 `csr` 环境**：`csr` 环境的 M 级陷阱向量把
//   cause 8 / 9 / 11 当 **PASS** ⇒ ⇒ 判决要是走 `ecall` 那条路，在 S 模式
//   里 `ecall` 是 cause 9 ⇒ ⇒ **假绿** ⇒ ⇒ `smode` 环境的判决是**直接写
//   `tohost`**（不经陷阱路径）⇒ ⇒ 判决在 S 模式里也能如实报出来。
// * **判决字落在条目 1 里** ⇒ ⇒ 判决那笔写**任何**特权级都放行 ⇒ ⇒ 所以
//   **不需要**在判决路径上去清 `MPRV`（清 `MPRV` 在 S 模式里是**非法指令**
//   ⇒ ⇒ 反而会制造一条假故障）⇒ ⇒ 同理，判决路径**不碰任何 M 级 CSR**。
// * **文件自包含**（不包含任何 riscv-tests 源码）⇒ ⇒ 上游树换形状也不影响
//   它（与 `unmapped_store.S` / `pmp_deny.S` 同一条纪律）。
#include "riscv_test.h"

RVTEST_RV32M
RVTEST_CODE_BEGIN

  // =====================================================================
  // 0. 预填 —— **在**配 PMP **之前**做（那时 `MPRV` 还是 0 ⇒ ⇒ M 模式
  //    的访存豁免 PMP ⇒ ⇒ DENY 条目咬不到这两个值）
  // =====================================================================
  li    t1, 0x80040000        // T —— DENY 条目盖住的那个地址
  li    t3, 0xfeedface
  sw    t3, 0(t1)             // 格 A / 格 C 必须读回的就是它
                                // ⚠️ **同一个字**还是格 E 的「取指目标」上
                                // 的内容 ⇒ ⇒ 它**不是**一条合法指令 ⇒ ⇒ 万一
                                // 取指被放行，它会被当成指令执行 ⇒ ⇒ 非法指令
                                // （cause 2）⇒ ⇒ 「没有被拒」这件事看得见。

  li    t1, 0x80002000        // 控制地址 —— 在 ALLOW 里、不在 DENY 里
  li    t3, 0x5a5a5a5a
  sw    t3, 0(t1)             // 控制组必须读回的就是它

  // =====================================================================
  // 1. PMP 配置（配置 A）
  // =====================================================================
  // ⚠️ `pmpcfg0` **先**写一次「两条都放行」⇒ ⇒ 任何中间态都不会出现
  //    「DENY 条目盖住代码或判决字」⇒ ⇒ 程序不会被自己的配置锁在外面。
  li    t0, 0x1f1f            // 条目 0 = 条目 1 = 0x1f（NAPOT，R + W + X）
  csrw  pmpcfg0, t0
  li    t0, 0x200101ff        // 条目 0：NAPOT，4 KiB @ 0x80040000
  csrw  pmpaddr0, t0
  li    t0, 0x2001ffff        // 条目 1：NAPOT，1 MiB @ 0x80000000
  csrw  pmpaddr1, t0
  li    t0, 0x1f18            // 条目 0 = 0x18（NAPOT，无权限）⇒ DENY
                                // 条目 1 = 0x1f（NAPOT，R + W + X）⇒ ALLOW
  csrw  pmpcfg0, t0

  // =====================================================================
  // 2. 控制组 —— 「这个用例是活的」
  // =====================================================================
  // ⚠️ 控制**特意**跑在 PMP **真的生效**的窗口里（`MPRV` = 1、`MPP` = 0
  //    ⇒ ⇒ 有效特权级 = U）⇒ ⇒ 它和格 B 同窗口 ⇒ ⇒ 它证明的正是「条目 1
  //    真的给了权限」。
  li    t0, 0x20000           // mstatus.MPRV
  csrs  mstatus, t0
  li    t0, 0x1800            // mstatus.MPP
  csrc  mstatus, t0           // ⇒ MPP = 0（U 模式）⇒ PMP 真的生效
  li    t1, 0x80002000
  lw    t2, 0(t1)             // 必须放行（条目 1 有 R）
  li    t3, 0x5a5a5a5a
  bne   t2, t3, control_failed

  // =====================================================================
  // 3. 格 A —— M 模式 · `MPRV` = 0 ⇒ ⇒ 有效特权级 = M ⇒ ⇒ **豁免**
  //    ⇒ ⇒ 放行，且读回的值必须是预填的那个
  // =====================================================================
  li    s3, 1                 // 相位 = A
  li    t0, 0x20000           // MPRV
  csrc  mstatus, t0           // ⇒ MPRV = 0
  li    t0, 0x1800            // MPP
  csrc  mstatus, t0           // ⇒ MPP = 0（U）
                                // ⚠️ `MPRV` = 0 时 `MPP` 不参与计算 ⇒ ⇒
                                //    这里取 0 是**更强**的选法：一个「不管
                                //    `MPRV` 一律用 `MPP`」的实现会在这一格
                                //    拒掉 ⇒ ⇒ 格 A 就能抓住它。
  li    t1, 0x80040000
  lw    t2, 0(t1)             // <- 必须**放行**
  li    t3, 0xfeedface
  bne   t2, t3, cell_a_value_failed

  // =====================================================================
  // 4. 格 B —— M 模式 · `MPRV` = 1 · `MPP` = 0（U）⇒ ⇒ 有效特权级 = U
  //    ⇒ ⇒ PMP 生效 ⇒ ⇒ **拒绝** ⇒ ⇒ 陷阱，`mcause` = 5
  // =====================================================================
  li    s3, 2                 // 相位 = B
  li    t0, 0x20000
  csrs  mstatus, t0           // ⇒ MPRV = 1
  li    t0, 0x1800
  csrc  mstatus, t0           // ⇒ MPP = 0（U）⇒ 数据访存的有效特权级是 U
  li    s0, 5                 // 期望的 mcause（load access fault）
  la    s1, faulting_load_b   // 期望的 mepc（那条出错的指令）
  li    t1, 0x80040000
faulting_load_b:
  lw    t2, 0(t1)             // <- 必须**被拒**
  j     cell_b_not_denied     // （走不到：陷阱先把控制流带走了）

  // =====================================================================
  // 5. 格 C —— M 模式 · `MPRV` = 1 · `MPP` = 3（M）⇒ ⇒ 有效特权级 = **M**
  //    ⇒ ⇒ **豁免**⇒ ⇒ 放行，且读回的值必须是预填的那个
  //    （⚠️ 这一格从格 B 的陷阱处理器**跳**进来）
  // =====================================================================
cell_c_setup:
  li    s3, 3                 // 相位 = C
  li    t0, 0x20000
  csrs  mstatus, t0           // ⇒ MPRV = 1
  li    t0, 0x1800
  csrs  mstatus, t0           // ⇒ MPP = 3（M）⇒ 有效特权级是 M ⇒ 豁免
  li    t1, 0x80040000
  lw    t2, 0(t1)             // <- 必须**放行**
  li    t3, 0xfeedface
  bne   t2, t3, cell_c_value_failed

  // =====================================================================
  // 6. 格 D 的准备 —— **S 模式** · `MPRV` = 0 ⇒ ⇒ 有效特权级 = **S** ⇒ ⇒
  //    PMP 生效 ⇒ ⇒ **拒绝** ⇒ ⇒ 陷阱，`mcause` = 5
  // =====================================================================
cell_d_setup:
  li    t0, 0x20000
  csrc  mstatus, t0           // ⇒ MPRV = 0 ⇒ S 模式的访存按**当前**特权级
                                //    （S）算 ⇒ ⇒ PMP 生效
  // ⚠️⚠️ `MPP` 是**两位的 WARL 字段**，`csrs` 只**置位**⇒ ⇒ 必须**先清
  //    干净**（`csrc`）**再置位**（`csrs`）⇒ ⇒ 否则 `MPP` 会被「或」成 3
  //    ⇒ ⇒ `mret` 落回 **M 模式**⇒ ⇒ 格 D / 格 E 根本没被测到（而且
  //    **两侧会同时**报同一个失败码 ⇒ ⇒ 对拍器看成「两边一致」⇒ ⇒
  //    **假绿**）。
  li    t0, 0x1800            // MPP 的两位掩码
  csrc  mstatus, t0           // ⇒ MPP = 0
  li    t0, 0x800             // MPP = 1（S）
  csrs  mstatus, t0           // ⇒ MPP = 1
  la    t0, in_s_mode
  csrw  mepc, t0
  mret                        // ⇒ ⇒ hart 落在 **S 模式**
in_s_mode:
  // ---- 「我们真的在 S 模式」的**自证** ----
  li    s3, 5                 // 相位 = 「S 模式的证明」
  csrr  t0, mstatus           // ⚠️ S 模式里读 M 级 CSR ⇒ **非法指令**
                                //    （cause 2）⇒ ⇒ 被委托 ⇒ ⇒ 落到 **S 级**
                                //    处理器 ⇒ ⇒ 「能走到 S 级处理器」本身就是
                                //    「我们在 S 模式」的证据。
  // ⇒ ⇒ 走到这里 ⇒ ⇒ 那条指令**没有陷** ⇒ ⇒ 我们**没有**进 S 模式
  li    TESTNUM, 15
  j     report_fail

  // =====================================================================
  // 失败路径 —— 每个格子自己的失败码
  // =====================================================================
control_failed:
  li    TESTNUM, 13
  j     report_fail

cell_a_value_failed:
  li    TESTNUM, 4
  j     report_fail

cell_b_not_denied:
  li    TESTNUM, 5
  j     report_fail

cell_c_value_failed:
  li    TESTNUM, 9
  j     report_fail

cell_d_not_denied:
  li    TESTNUM, 10
  j     report_fail

report_pass:
  RVTEST_PASS

report_fail:
  // ⚠️ 这条路径**可能**在 **S 模式**里跑（格 D / 格 E 的失败）⇒ ⇒ 它**不碰
  //    任何 M 级 CSR**（读 `mstatus` 在 S 模式里是非法指令 ⇒ ⇒ 会再陷一次
  //    ⇒ ⇒ 变成死循环）⇒ ⇒ 也不需要清 `MPRV`（判决字在条目 1 里 ⇒ ⇒ 任何
  //    特权级都放行）。
  RVTEST_FAIL

  // =====================================================================
  // M 级陷阱处理器
  // =====================================================================
  // ⚠️ 它处理**四**种可能：
  //   * 相位 = B / D / E ⇒ ⇒ 那是**期望中**的拒绝 ⇒ ⇒ 查 `mcause` 与 `mepc`
  //     ⇒ ⇒ 通过就继续往下跑；
  //   * 相位 = A / C ⇒ ⇒ 那一格**不该**陷阱 ⇒ ⇒ 平台**过严**；
  //   * 相位对不上（含相位 = 5 的「S 模式证明」）⇒ ⇒ 意料之外的陷阱。
  .align 2
  .globl mtvec_handler
mtvec_handler:
  csrr  t0, mcause
  csrr  t1, mepc
  li    t2, 2
  beq   s3, t2, trap_in_cell_b
  li    t2, 3
  beq   s3, t2, trap_in_cell_c
  li    t2, 4
  beq   s3, t2, trap_in_cell_d
  li    t2, 6
  beq   s3, t2, trap_in_cell_e
  li    t2, 1
  beq   s3, t2, trap_in_cell_a
  // 没有相位匹配 ⇒ ⇒ 意料之外的陷阱
  li    TESTNUM, 14
  j     report_fail

trap_in_cell_a:
  // ⚠️ 格 A **不该**陷阱 ⇒ ⇒ 平台拒掉了一次参考侧放行的访问 ⇒ ⇒ 平台**过严**
  li    TESTNUM, 3
  j     report_fail

trap_in_cell_c:
  // ⚠️ 格 C **不该**陷阱 ⇒ ⇒ 平台过严（D-153 的 (a)：`MPP` = 3 时有效特权级
  //    是 M ⇒ ⇒ 应当豁免）
  li    TESTNUM, 8
  j     report_fail

trap_in_cell_b:
  li    t2, 5
  bne   t0, t2, cell_b_wrong_cause     // mcause 必须是 5（load access fault）
  bne   t1, s1, cell_b_wrong_mepc      // mepc 必须是那条出错的指令
  // ⇒ ⇒ 这次拒绝正是参考侧报的那个 ⇒ ⇒ 接着跑格 C。
  // ⚠️ **不 `mret`**：hart 必须待在 M 模式 —— 一次 `mret` 会按 `MPP` = 0
  //    回到 U 模式 ⇒ ⇒ 后面的格就都跑不动了 ⇒ ⇒ 所以直接**跳**过去。
  j     cell_c_setup

cell_b_wrong_cause:
  li    TESTNUM, 6
  j     report_fail

cell_b_wrong_mepc:
  li    TESTNUM, 7
  j     report_fail

trap_in_cell_d:
  li    t2, 5
  bne   t0, t2, cell_d_wrong_cause
  bne   t1, s1, cell_d_wrong_mepc
  // ⇒ ⇒ 格 D 成立 ⇒ ⇒ 回到 **S 模式**跑格 E（取指那一条）。
  // ⚠️ 这个陷阱是以 **M 模式**处理的 ⇒ ⇒ 要回 S 模式 ⇒ ⇒ 一次 `mret`
  //    （`MPP` = 1）⇒ ⇒ 而 `MPP` 又是那位两位的 WARL 字段 ⇒ ⇒ 同样
  //    **先清干净再置位**。
  li    t2, 0x1800
  csrc  mstatus, t2         // ⇒ MPP = 0
  li    t2, 0x800
  csrs  mstatus, t2         // ⇒ MPP = 1（S）
  la    t0, cell_e_setup
  csrw  mepc, t0
  mret                        // ⇒ ⇒ 回到 **S 模式**

cell_d_wrong_cause:
  li    TESTNUM, 11
  j     report_fail

cell_d_wrong_mepc:
  li    TESTNUM, 12
  j     report_fail

trap_in_cell_e:
  // ⚠️ 格 E 的判据钉在「**目标地址的那次取指**」上 ⇒ ⇒ `mcause` 必须是 1
  //    （instruction access fault）且 `mepc` 必须是**目标地址**。
  li    t2, 1
  bne   t0, t2, cell_e_not_denied    // 取指**没有**被拒（多半是预填的那个字
                                    // 被当成指令执行了 ⇒ ⇒ cause 2）
  bne   t1, s1, cell_e_wrong_mepc    // 被拒了但报的不是目标地址
  // ⇒ ⇒ 五格全部成立 ⇒ ⇒ PASS
  j     report_pass

cell_e_not_denied:
  li    TESTNUM, 16
  j     report_fail

cell_e_wrong_mepc:
  li    TESTNUM, 17
  j     report_fail

  // =====================================================================
  // S 级陷阱处理器
  // =====================================================================
  // ⚠️ **只有**在 S 模式里才会走到这里 ⇒ ⇒ 「我们真的在 S 模式」这件事
  //    由**本处理器被进入**这件事本身证明 ⇒ ⇒ 格 D / 格 E 因此不会退化成
  //    「在 M 模式里做了一次访问」。
  //
  // ⚠️ 这里可能是三件事：
  //   ① 「S 模式证明」那条非法指令（`scause` = 2）⇒ ⇒ 接着跑格 D 的访问；
  //   ② ⚠️ **格 E 的「取指没有被拒」**：取指被放行 ⇒ ⇒ 目标地址上预填的那个
  //      字（`0xfeedface`）被当成指令执行 ⇒ ⇒ 非法指令（cause 2）⇒ ⇒ 而
  //      cause 2 **是**被委托的 ⇒ ⇒ **它落在这里**（而不是 `mtvec`）⇒ ⇒
  //      ⇒ ⇒ 所以这一格「没有被拒」的证据是一条**被委托**的非法指令陷阱。
  //   ③ 别的被委托的陷阱 ⇒ ⇒ 意料之外。
  .align 2
  .globl stvec_handler
stvec_handler:
  li    t2, 5
  beq   s3, t2, s_mode_proof
  li    t2, 6
  beq   s3, t2, s_cell_e_not_denied
  // ⇒ ⇒ 别的被委托的陷阱 ⇒ ⇒ 意料之外
  li    TESTNUM, 14
  j     report_fail

s_cell_e_not_denied:
  // ⚠️ 必须是非法指令（cause 2）⇒ ⇒ 那正是「预填的那个字被当成指令执行了」
  //    ⇒ ⇒ 即「目标地址的那次**取指没有被拒**」。
  csrr  t0, scause
  li    t2, 2
  bne   t0, t2, s_unexpected_trap
  li    TESTNUM, 16
  j     report_fail

s_mode_proof:
  csrr  t0, scause
  li    t2, 2
  bne   t0, t2, s_unexpected_trap   // 必须是非法指令（cause 2）
  // ⇒ ⇒ S 模式的证明成立 ⇒ ⇒ 接着跑格 D 的访问
  li    s3, 4                 // 相位 = D
  li    s0, 5                 // 期望的 mcause
  la    s1, faulting_load_d   // 期望的 mepc
  li    t1, 0x80040000
faulting_load_d:
  lw    t2, 0(t1)             // <- 必须**被拒**
  j     cell_d_not_denied     // （走不到：陷阱先把控制流带走了）

s_unexpected_trap:
  li    TESTNUM, 14
  j     report_fail

  // =====================================================================
  // 7. 格 E —— **S 模式**下的**取指**落进一条**没有 `X` 权限**的条目
  //    ⇒ ⇒ 必须**被拒**（`mcause` = 1，instruction access fault）
  // =====================================================================
  // ⚠️ 跳转指令本身在条目 1（有 `X`）里 ⇒ ⇒ **它的那次取指成功** ⇒ ⇒
  //    被拒的是**落在目标地址的那次取指** ⇒ ⇒ 判据钉在 `mepc` == 目标地址。
cell_e_setup:
  li    s3, 6                 // 相位 = E
  li    s0, 1                 // 期望的 mcause（instruction access fault）
  li    s1, 0x80040000        // 期望的 mepc（**目标地址**）
  li    t0, 0x80040000
  jr    t0                    // <- 跳进条目 0（NAPOT，无 R/W/X ⇒ ⇒ 没有 X）
cell_e_never:
  // ⚠️ 走不到：目标地址的那次取指要么被拒（cause 1 ⇒ ⇒ 陷阱）⇒ ⇒ 要么被
  //    放行 ⇒ ⇒ 那里预填的 `0xfeedface` 被当成指令执行 ⇒ ⇒ 非法指令
  //    （cause 2）⇒ ⇒ 陷阱。⇒ ⇒ 两条路都会离开这里。
  li    TESTNUM, 16
  j     report_fail

